// Capturas del manual de Solicitud de Transporte: Entrega, Recojo y Punto a punto, paso a paso.
// Requiere la app en http://localhost:3000 contra el Supabase simulado (fake-supabase.cjs). Salida: OUT=<carpeta>.
const { chromium } = require(require('child_process').execSync('npm root -g').toString().trim() + '/playwright')
const path = require('path')
const OUT = process.env.OUT || path.join(__dirname, 'img')
const BASE = 'http://localhost:3000/solicitudes'
const b64 = s => Buffer.from(s).toString('base64url')
const exp = Math.floor(Date.now() / 1000) + 86400
const jwt = [b64(JSON.stringify({ alg: 'HS256', typ: 'JWT' })), b64(JSON.stringify({ sub: '11111111-1111-4111-8111-111111111111', role: 'authenticated', aud: 'authenticated', exp, email: 'ana.torres@jrm.pe' })), 'firma'].join('.')
const session = { access_token: jwt, refresh_token: 'demo', expires_at: exp, expires_in: 86400, token_type: 'bearer', user: { id: '11111111-1111-4111-8111-111111111111', aud: 'authenticated', role: 'authenticated', email: 'ana.torres@jrm.pe', app_metadata: {}, user_metadata: {} } }
const plusDays = n => { const d = new Date(); d.setDate(d.getDate() + n); return d.toISOString().slice(0, 10) }

;(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'] })
  const open = async () => {
    const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5, timezoneId: 'America/Lima', locale: 'es-PE' })
    await ctx.addCookies([{ name: 'sb-localhost-auth-token', value: 'base64-' + b64(JSON.stringify(session)), domain: 'localhost', path: '/' }])
    await ctx.addInitScript(() => { try { localStorage.setItem('userRole', 'admin') } catch { /* sin almacenamiento */ } })
    const page = await ctx.newPage()
    page.on('pageerror', e => console.log('PAGEERROR', e.message))
    await page.route('**/api/sunat**', r => r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ nombre: 'TRANSPORTES Y SERVICIOS NORTE S.A.C.', direccion: 'AV. ARGENTINA 2450', distrito: 'CALLAO', provincia: 'CALLAO', departamento: 'CALLAO', estado: 'ACTIVO', condicion: 'HABIDO' }) }))
    await page.goto(BASE, { waitUntil: 'networkidle' })
    const shot = async name => { await page.waitForTimeout(700); await page.screenshot({ path: path.join(OUT, name + '.png') }); console.log('shot', name) }
    const sec = async (id, name) => { const l = page.locator('#' + id); await l.scrollIntoViewIfNeeded(); await page.waitForTimeout(500); await l.screenshot({ path: path.join(OUT, name + '.png') }); console.log('sec', name) }
    const openModal = async (type) => {
      await page.getByRole('button', { name: 'Nueva Solicitud' }).click()
      await page.locator('#req-servicio').waitFor()
      if (type) await page.locator('#req-servicio').getByRole('radio', { name: new RegExp(type) }).click()
      await page.locator('#req-servicio select').first().selectOption('Logística')
    }
    const tall = () => page.setViewportSize({ width: 1440, height: 3600 })
    const normal = () => page.setViewportSize({ width: 1440, height: 900 })
    const fillDate = async (days, time) => { await page.locator('#req-fecha input[type=date]').fill(plusDays(days)); await page.locator('#req-fecha input[type=time]').fill(time) }
    const finish = async (prefix) => {
      await page.locator('#req-descarga').getByText('No requiere').click()
      await sec('req-descarga', prefix + '-descarga')
      await normal(); await page.locator('#req-descarga').scrollIntoViewIfNeeded()
      await shot(prefix + '-revisar')
      await page.getByRole('button', { name: 'Enviar solicitud' }).click()
      await page.waitForTimeout(1500)
      await shot(prefix + '-enviada')
    }
    return { page, ctx, shot, sec, openModal, tall, normal, fillDate, finish }
  }

  // ===== Pantalla general
  let s = await open()
  await s.shot('g-listado')
  await s.page.locator('table tbody tr').first().locator('button').last().click()
  await s.shot('g-acciones')
  await s.page.keyboard.press('Escape')
  await s.openModal()
  await s.shot('g-modal')
  await s.ctx.close()

  // ===== ENTREGA (con alta de OT y cliente)
  s = await open()
  await s.openModal('Despacho'); await s.tall()
  await s.sec('req-servicio', 'e-servicio')
  await s.page.getByRole('button', { name: /No existe la OT/ }).click()
  await s.sec('req-ot', 'e-ot-nueva')
  await s.page.locator('#req-ot').getByRole('button', { name: 'Nuevo cliente' }).click()
  await s.page.getByPlaceholder('20XXXXXXXXX').fill('20555555551')
  await s.page.getByRole('button', { name: 'SUNAT' }).click()
  await s.page.waitForTimeout(800)
  await s.sec('req-ot', 'e-cliente-sunat')
  await s.page.getByRole('button', { name: 'Registrar y usar en esta OT' }).click()
  await s.page.waitForTimeout(800)
  const ot = s.page.locator('#req-ot')
  await ot.getByPlaceholder('16584').fill('16575')
  await ot.getByPlaceholder('Ej. Av. Industrial 123').fill('Av. Néstor Gambetta 3120, Callao')
  await ot.getByPlaceholder('Ej. LIMA').first().fill('CALLAO')
  await ot.getByPlaceholder('Ej. LIMA').nth(1).fill('CALLAO')
  await ot.getByPlaceholder('Ej. ATE').fill('CALLAO')
  await ot.getByPlaceholder('0.00').fill('15000')
  await s.sec('req-ot', 'e-ot-datos')
  await ot.getByRole('button', { name: 'Registrar OT y usarla' }).click()
  await s.page.waitForTimeout(2000)
  await s.page.locator('#req-ot input[type=checkbox]').first().check()
  await s.sec('req-ot', 'e-ot-seleccionada')
  await s.sec('req-ruta', 'e-ruta')
  await s.fillDate(3, '09:00')
  await s.sec('req-fecha', 'e-fecha')
  await s.page.locator('#req-carga textarea').fill('12 vigas de acero H 8 m y 4 planchas estructurales para el proyecto Callao')
  await s.page.waitForTimeout(1200)
  await s.sec('req-carga', 'e-carga')
  await s.finish('e')
  await s.ctx.close()

  // ===== RECOJO (proveedor → planta)
  s = await open()
  await s.openModal('Recojo'); await s.tall()
  await s.sec('req-servicio', 'r-servicio')
  await s.sec('req-ot', 'r-ot-opcional')
  const prov = s.page.locator('#req-proveedor')
  await prov.getByText('Buscar por razón social o RUC…').click()
  await s.page.waitForTimeout(400)
  await s.sec('req-proveedor', 'r-proveedor-buscar')
  await s.page.getByText('ACEROS INDUSTRIALES DEL PERÚ', { exact: false }).last().click()
  await s.page.waitForTimeout(600)
  await s.sec('req-proveedor', 'r-proveedor-elegido')
  await prov.getByRole('button', { name: 'Nuevo punto' }).click().catch(() => console.log('sin nuevo punto'))
  await prov.getByPlaceholder('Nombre del punto *').fill('Planta Ventanilla').catch(() => {})
  await prov.getByPlaceholder('Dirección exacta *').fill('Av. Industrial Mz. B Lt. 4, Ventanilla').catch(() => {})
  await prov.getByPlaceholder('Distrito *').fill('VENTANILLA').catch(() => {})
  await s.sec('req-proveedor', 'r-nuevo-punto')
  await prov.getByRole('button', { name: 'Cancelar' }).first().click().catch(() => {})
  await prov.getByRole('button', { name: 'Nuevo proveedor' }).click()
  await prov.getByPlaceholder('RUC *').fill('20100070970')
  await prov.getByPlaceholder('Razón social *').fill('FERRETERÍA INDUSTRIAL SAN MARTÍN S.A.C.')
  await s.sec('req-proveedor', 'r-nuevo-proveedor')
  await prov.getByRole('button', { name: 'Cancelar' }).first().click().catch(() => {})
  await s.page.waitForTimeout(400)
  await s.sec('req-ruta', 'r-ruta')
  await s.fillDate(2, '10:00')
  await s.sec('req-fecha', 'r-fecha')
  await s.page.locator('#req-carga textarea').fill('Recojo de 30 rollos de alambrón y 2 paletas de pernos')
  await s.page.locator('#req-carga select[aria-label="Tipo de documento"]').selectOption('OC')
  await s.page.locator('#req-carga input[aria-label="Número de documento"]').fill('57731')
  await s.sec('req-carga', 'r-carga-oc')
  await s.finish('r')
  await s.ctx.close()

  // ===== PUNTO A PUNTO (proveedor → destino externo)
  s = await open()
  await s.openModal('Punto a punto'); await s.tall()
  await s.sec('req-servicio', 'p-servicio')
  await s.page.locator('#req-proveedor').getByText('Buscar por razón social o RUC…').click()
  await s.page.getByText('ACEROS INDUSTRIALES DEL PERÚ', { exact: false }).last().click()
  await s.page.waitForTimeout(600)
  await s.sec('req-proveedor', 'p-proveedor')
  const ruta = s.page.locator('#req-ruta')
  await ruta.locator('input[list="historical-delivery-addresses"]').fill('Almacén de obra Proyecto Andino, Km 45 Panamericana Sur')
  await ruta.getByPlaceholder('Ej. LIMA').nth(1).fill('LIMA').catch(() => {})
  await ruta.getByPlaceholder('Ej. LIMA').last().fill('CAÑETE').catch(() => {})
  await ruta.getByPlaceholder('Ej. ATE').fill('CHILCA')
  await s.page.waitForTimeout(600)
  await s.sec('req-ruta', 'p-ruta')
  await s.fillDate(2, '08:00')
  await s.sec('req-fecha', 'p-fecha')
  await s.page.locator('#req-carga textarea').fill('Traslado directo de 8 vigas metálicas del proveedor al almacén de obra')
  await s.page.locator('#req-carga select[aria-label="Tipo de documento"]').selectOption('OS')
  await s.page.locator('#req-carga input[aria-label="Número de documento"]').fill('12045')
  await s.page.waitForTimeout(1200)
  await s.sec('req-carga', 'p-carga-os')
  await s.finish('p')
  await s.ctx.close()
  await browser.close()
})()
