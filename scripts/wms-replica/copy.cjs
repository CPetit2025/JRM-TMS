// Fase 4: copia la historia del modelo de almacén del TMS (producción) a la base WMS, de base a base con COPY.
// Solo lee del TMS. En el WMS escribe únicamente en las tablas replicadas y exige que estén vacías.
// Uso: node copy.cjs <destino: staging|wms> [tabla ...]
//   Antes y después, con el usuario dueño (supabase db query): node copy.cjs sql pre|post > archivo.sql
//   La copia escribe con el usuario temporal wms_replica_copy (COPY_PASSWORD); se crea antes y se borra después.
//   pre: identidades ALWAYS → BY DEFAULT y permiso temporal al usuario de la CLI; post: lo revierte y ajusta secuencias.
const { connect } = require('./db.cjs')
const { to: copyTo, from: copyFrom } = require('pg-copy-streams')
const { pipeline } = require('node:stream/promises')
const o = require('./esquema.json')

const PARENTS = ['apa_imports', 'apt_uploads', 'erp_derive_days', 'inv_uploads']
// Un padre se copia en la misma foto que sus hijos: si los hijos siguen vacíos, el padre se vacía y se vuelve a copiar
const CHILDREN = { apt_uploads: ['apt_movements'], inv_uploads: ['inv_movements', 'inv_stock_snapshots', 'inv_upload_chunks'], erp_derive_days: ['erp_derive_stock', 'erp_derive_guias'] }
const target = process.argv[2]
if (target === 'sql') {
  const tables = o.tables.map(t => 'public.' + t.name).join(', ')
  const ids = [['apt_movements', 'id'], ['apt_flow_pieces', 'id'], ['apt_operational_readiness_history', 'id']]
  const L = process.argv[3] === 'pre'
    ? [...ids.map(([t, c]) => `ALTER TABLE public.${t} ALTER COLUMN ${c} SET GENERATED BY DEFAULT;`), 'ALTER TABLE public.erp_derive_days DISABLE TRIGGER erp_derive_days_rule_version;', `GRANT SELECT, INSERT ON ${tables} TO cli_login_postgres;`,
      // COPY no admite RLS: se desactiva durante la copia y, mientras tanto, la aplicación no ve estas tablas
      `REVOKE ALL ON ${tables} FROM authenticated;`, ...o.tables.map(t => `ALTER TABLE public.${t.name} DISABLE ROW LEVEL SECURITY;`)]
    : [`REVOKE ALL ON ${tables} FROM cli_login_postgres;`, 'ALTER TABLE public.erp_derive_days ENABLE TRIGGER erp_derive_days_rule_version;',
       ...o.tables.map(t => `ALTER TABLE public.${t.name} ENABLE ROW LEVEL SECURITY;`), ...o.security.filter(x => x.startsWith('GRANT ')),
       ...ids.map(([t, c]) => `ALTER TABLE public.${t} ALTER COLUMN ${c} SET GENERATED ALWAYS;\nSELECT setval(pg_get_serial_sequence('public.${t}', '${c}'), coalesce((SELECT max(${c}) FROM public.${t}), 0) + 1, false);`),
       ...o.sequences.map(s => /EXISTS (\S+);/.exec(s)[1]).map(seq => `SELECT setval('${seq}', coalesce((SELECT max(id) FROM public.${seq.replace(/_id_seq$/, '')}), 0) + 1, false);`)]
  console.log(L.join('\n')); process.exit(0)
}
const only = process.argv.slice(3)
if (!['staging', 'wms'].includes(target)) { console.error('Uso: node copy.cjs <staging|wms> [tabla ...]'); process.exit(2) }

;(async () => {
  const src = await connect('tms', { copy: true })
  const prep = await connect(target, { copy: true })
  for (const [parent, kids] of Object.entries(CHILDREN)) {
    const filled = (await prep.query(`select ${kids.map(k => `(select count(*) from public.${k})`).join(' + ')} n`)).rows[0].n
    if (Number(filled) === 0) await prep.query(`DELETE FROM public.${parent}`)
  }
  await prep.end()
  await src.query('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY')
  const names = o.tables.map(t => t.name).filter(n => !only.length || only.includes(n))
  const ordered = [...PARENTS.filter(n => names.includes(n)), ...names.filter(n => !PARENTS.includes(n))]
  let total = 0
  for (const name of ordered) {
   for (let intento = 1; intento <= 3; intento++) {
    const dst = await connect(target, { copy: true })
    let ok = false
    const cols = (await dst.query(`select a.attname from pg_attribute a where a.attrelid = $1::regclass and a.attnum > 0 and not a.attisdropped and a.attgenerated = ''
      and a.attname = any($2) order by a.attnum`, [`public.${name}`, o.tables.find(t => t.name === name).cols])).rows.map(r => `"${r.attname}"`)
    const n0 = Number((await dst.query(`select count(*) n from public.${name}`)).rows[0].n)
    if (n0 > 0) { console.log(`${name}: destino con ${n0} filas, se omite`); await dst.end(); break }
    await dst.query('BEGIN')
    try {
      const t0 = Date.now()
      await pipeline(src.query(copyTo(`COPY (SELECT ${cols.join(', ')} FROM public.${name}) TO STDOUT WITH (FORMAT binary)`)),
        dst.query(copyFrom(`COPY public.${name} (${cols.join(', ')}) FROM STDIN WITH (FORMAT binary)`)))
      await dst.query('COMMIT')
      const [a, b] = await Promise.all([src.query(`select count(*) n from public.${name}`), dst.query(`select count(*) n from public.${name}`)])
      total += Number(b.rows[0].n)
      console.log(`${name}: ${b.rows[0].n}/${a.rows[0].n} filas en ${Math.round((Date.now() - t0) / 1000)} s${a.rows[0].n === b.rows[0].n ? '' : '  ← DISTINTO'}`)
      ok = true
    } catch (e) { await dst.query('ROLLBACK').catch(() => {}); console.log(`${name}: ERROR (intento ${intento}) ${e.message}`) }
    await dst.end().catch(() => {})
    if (ok) break
   }
  }
  console.log(`Total copiado: ${total} filas`)
  await src.query('COMMIT'); await src.end()
})().catch(e => { console.error('ERROR', e.message); process.exit(1) })
